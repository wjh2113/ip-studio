/* 外部来的文本（抓到的网页、榜单、转写、作者粘进来的素材）用标签包起来，和指令分开。
   里面如果恰好出现「忽略上面的要求」之类的话，模型也应当把它当资料而不是指令。
   标签名本身出现在内容里时拆开，免得内容把标签提前「关掉」。 */
export const fence = (tag, text) => {
  const body = String(text ?? '').split(`</${tag}>`).join(`</ ${tag}>`);
  return `<${tag}>\n${body}\n</${tag}>`;
};
